// Turns src/ds/icons/svg/*.svg into src/ds/icons/icons.generated.ts.
// Single-colour icons get their main fill replaced by currentColor so they follow CSS `color`.
// Add a new icon: drop the SVG into src/ds/icons/svg/ (kebab-case name) and run `npm run icons`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = `${root}src/ds/icons/svg/`;

// Icons whose colours are part of the artwork.
const MULTICOLOR = new Set(['compass', 'pin-station', 'heart-fill']);
const MONO_COLORS = /(fill|stroke)="#(3A4040|333333|FFB700)"/gi;

const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((file) => {
    const name = file.replace(/\.svg$/, '');
    let svg = readFileSync(dir + file, 'utf8').replace(/<!--[\s\S]*?-->/g, '').trim();
    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24';
    let body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    // Make ids unique per icon so two different icons never share a clip-path/filter id.
    body = body.replace(/id="([^"]+)"/g, `id="${name}-$1"`).replace(/#([A-Za-z_][\w-]*)\)/g, `#${name}-$1)`)
      .replace(/href="#([^"]+)"/g, `href="#${name}-$1"`);
    if (!MULTICOLOR.has(name)) body = body.replace(MONO_COLORS, '$1="currentColor"');
    return [name, { viewBox, body: body.replace(/\s*\n\s*/g, ' ') }];
  });

const out = [
  '// AUTO-GENERATED by scripts/build-icons.mjs – do not edit by hand.',
  `export const icons = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;`,
  'export type IconName = keyof typeof icons;',
  '',
];
writeFileSync(`${root}src/ds/icons/icons.generated.ts`, out.join('\n'));
console.log(`icons.generated.ts: ${entries.length} icons`);
