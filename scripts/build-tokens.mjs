// Generates src/ds/tokens/tokens.css from the Figma variables export.
// Re-run whenever design exports a new design-tokens/figma-variables.json.
//
//   Primitive collection  -> :root { --neutral-800: #3a4040; --dim-16: 16px; ... }
//   Semantic collection   -> :root { --text-primary: var(--neutral-800); ... }   (Light)
//                            [data-theme='dark'] { ... }                         (Dark)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = JSON.parse(readFileSync(`${root}design-tokens/figma-variables.json`, 'utf8'));

const byId = new Map(src.variables.map((v) => [v.id, v]));
const cssName = (name) => `--${name.trim().toLowerCase().replace(/[\s/]+/g, '-')}`;

const hex = ({ r, g, b, a = 1 }) => {
  const h = [r, g, b].map((c) => Math.round(c * 255).toString(16).padStart(2, '0')).join('');
  return a >= 0.999 ? `#${h}` : `#${h}${Math.round(a * 255).toString(16).padStart(2, '0')}`;
};

// Floats are px, except weights and other unitless scopes.
const unitless = (v) => v.scopes?.includes('FONT_WEIGHT') || /font\/weight/.test(v.name);

function literal(v, value) {
  if (v.resolvedType === 'COLOR') return hex(value);
  if (v.resolvedType === 'STRING') return `'${value}'`;
  if (v.resolvedType === 'FLOAT') return unitless(v) ? String(value) : `${+value.toFixed(3)}px`;
  return String(value);
}

function value(v, modeId) {
  const modes = v.valuesByMode;
  const raw = modes[modeId] ?? Object.values(modes)[0];
  if (raw && raw.type === 'VARIABLE_ALIAS') {
    const target = byId.get(raw.id);
    if (!target) throw new Error(`Missing alias target ${raw.id} for ${v.name}`);
    return `var(${cssName(target.name)})`;
  }
  return literal(v, raw);
}

const out = ['/* AUTO-GENERATED by scripts/build-tokens.mjs – do not edit by hand. */'];
for (const col of src.collections) {
  const vars = col.variableIds.map((id) => byId.get(id)).filter(Boolean);
  const isSemantic = col.modes.length > 1;
  for (const mode of col.modes) {
    const selector = isSemantic && mode.name.toLowerCase() === 'dark' ? "[data-theme='dark']" : ':root';
    out.push('', `/* ${col.name} – ${mode.name} */`, `${selector} {`);
    for (const v of vars) out.push(`  ${cssName(v.name)}: ${value(v, mode.modeId)};`);
    out.push('}');
  }
}

writeFileSync(`${root}src/ds/tokens/tokens.css`, `${out.join('\n')}\n`);
console.log(`tokens.css: ${src.variables.length} variables written`);
